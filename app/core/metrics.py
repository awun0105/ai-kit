"""Prometheus metrics configuration for the application.

This module sets up and configures Prometheus metrics for monitoring the application.
"""

from prometheus_client import (
    CONTENT_TYPE_LATEST,
    Counter,
    Gauge,
    Histogram,
    generate_latest,
)
from starlette.requests import Request
from starlette.responses import Response

# Request metrics
http_requests_total = Counter("http_requests_total", "Total number of HTTP requests", ["method", "endpoint", "status"])

http_request_duration_seconds = Histogram(
    "http_request_duration_seconds", "HTTP request duration in seconds", ["method", "endpoint"]
)

# Database metrics
db_connections = Gauge("db_connections", "Number of active database connections")

# Custom business metrics
orders_processed = Counter("orders_processed_total", "Total number of orders processed")

llm_inference_duration_seconds = Histogram(
    "llm_inference_duration_seconds",
    "Latency of the successful attempt, by the registry model that answered",
    ["model"],
    buckets=[0.5, 1.0, 2.0, 5.0, 10.0, 20.0, 30.0, 60.0],  # reasoning models often take 5-30 s
)


llm_stream_duration_seconds = Histogram(
    "llm_stream_duration_seconds",
    "Time spent processing LLM stream inference",
    ["model"],
    buckets=[0.1, 0.5, 1.0, 2.0, 5.0, 10.0],
)

llm_attempts_total = Counter(
    "llm_attempts_total",
    "LLM provider attempts by outcome",
    [
        "model",
        "outcome",
    ],  # success | rate_limited | quota_exhausted | overloaded | server_error | timeout | client_error | skipped_*
)

llm_calls_total = Counter(
    "llm_calls_total",
    "Logical LLM calls (after retries and failover); the SLI for the LLM availability SLO",
    ["outcome"],  # success | failed | client_error
)

llm_breaker_state = Gauge(
    "llm_breaker_state", "Circuit breaker state per model (0 closed, 1 half-open, 2 open)", ["model"]
)

rag_citation_issues_total = Counter(
    "rag_citation_issues_total",
    "Knowledge answers with citation problems",
    ["kind"],  # out_of_range: cites a source that was not retrieved; uncited: no citation at all
)

answer_cache_events_total = Counter(
    "answer_cache_events_total",
    "Answer cache lookups and writes",
    ["outcome"],  # hit_fresh | hit_stale | miss | stored
)

guardrail_events_total = Counter(
    "guardrail_events_total",
    "Guardrail interventions",
    ["rail", "action"],  # rail: input | tool | output; action: blocked_injection, redacted, ...
)

session_names_generated_total = Counter(
    "session_names_generated_total",
    "Total session names generated by the LLM",
    ["status"],  # "success" | "error"
)


async def metrics(request: Request) -> Response:
    """Expose every registered metric in the Prometheus text format."""
    return Response(generate_latest(), media_type=CONTENT_TYPE_LATEST)


def setup_metrics(app):
    """Expose ``/metrics``. Request metrics come from ``MetricsMiddleware``.

    ``starlette_prometheus`` was removed: it is unmaintained, duplicated
    ``MetricsMiddleware``, and crashes on FastAPI >= 0.16x included routers
    (``'_IncludedRouter' object has no attribute 'path'``), failing every /api request.

    Args:
        app: FastAPI application instance
    """
    app.add_route("/metrics", metrics)
